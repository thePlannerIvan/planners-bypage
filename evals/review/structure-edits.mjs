import {mkdtempSync,readFileSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
import {assert,jsonOutput,runNode,pass} from '../lib/assert.mjs';
import {moduleScript} from '../../scripts/lib/planners-modules.mjs';
const root = resolve(import.meta.dirname,'../..');
const run = (script,args) => jsonOutput(runNode(join(root,'scripts',script),args));
const dir = mkdtempSync(join(tmpdir(),'bypage-structure-edit-')), architecture = join(dir,'architecture.json'), reviewDir = join(dir,'review'), manifest = join(dir,'manifest.json');
const fixture = JSON.parse(readFileSync(join(root,'templates/page-architecture.json'),'utf8'));
fixture.sections.push({...fixture.sections[0],section_id:'sec-two',title:'Second chapter'});
fixture.pages.push({...structuredClone(fixture.pages[0]),page_number:2,section_id:'sec-two',title_intent:'Second page'});
writeFileSync(architecture,JSON.stringify(fixture,null,2));
writeFileSync(manifest,JSON.stringify({contract_version:'asset-manifest/1.1.0',asset_root:'.',assets:[]}));
const surface = run('start-storyline-review.mjs',['--architecture',architecture,'--assets',manifest,'--review-dir',reviewDir,'--surface-only','--legacy-review','true']).surface;
const browser = spawnSync(process.env.PLAYWRIGHT_PYTHON || 'python3',[moduleScript('planners-review-core','evals/exercise-content-review.py'),'--surface',surface,'--opaque'],{encoding:'utf8'});
assert(browser.status === 0,'browser behavior: '+browser.stdout+browser.stderr);
assert(run('review-inbox.mjs',['--surface',surface]).content_changed,'Structure edits must apply');
const actual = JSON.parse(readFileSync(architecture,'utf8'));
assert(actual.storyline_thesis === 'Human thesis' && actual.sections[1].title === 'Human chapter','Human storyline and section order');
assert(actual.pages[1].main_message === fixture.pages[0].main_message && actual.pages[1].content_blocks[0].content_requirement === 'Human expanded block','Native By-page fields retained');
assert(run('validate-page-architecture.mjs',[architecture,'--assets',manifest]).valid,'Independent structure contract valid');
assert(run('validate-storyline-review-feedback.mjs',['--feedback',join(reviewDir,'review-feedback.json'),'--architecture',architecture,'--assets',manifest]).valid,'Feedback bound to edited architecture');
pass('独立 By-page/PPT 资料入口：结构编辑与新 Hash 审阅');
